package com.merci.survivalkit.vein;

/** What sets Damar Kırıcı off. */
public enum Trigger {
	/** Hold the trigger key and break a block the usual way: the rest of its tree or vein follows. */
	HOLD_AND_BREAK,
	/** Look at a block and press the trigger key: the whole tree or vein goes, the block looked at too. */
	LOOK_AND_PRESS
}
